// One-shot porting helper: converts Deno edge functions in supabase/functions
// into worker-runtime handlers under src/lib/edge + thin API routes.
// Kept in-repo for traceability; safe to delete once the migration is verified.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const SRC = "supabase/functions";
const OUT = "src/lib/edge";
const ROUTES = "src/routes/api/public";
const SKIP = new Set(["mcp"]); // generated by the mcp-js Vite plugin

function transform(code) {
  return code
    .replace(/^import\s+\{\s*serve\s*\}\s+from\s+"https:\/\/deno\.land\/std[^"]*";\n/m, "")
    .replace(/"https:\/\/esm\.sh\/@supabase\/supabase-js@[^"]*"/g, '"@supabase/supabase-js"')
    .replace(/"npm:@supabase\/supabase-js@2\/cors"/g, '"../edge/shared/cors"')
    .replace(/"npm:@supabase\/supabase-js@[^"]*"/g, '"@supabase/supabase-js"')
    .replace(/"npm:zod@[^"]*"/g, '"zod"')
    .replace(/"npm:@paddle\/paddle-node-sdk"/g, '"@paddle/paddle-node-sdk"')
    .replace(/"\.\.\/_shared\/([a-zA-Z]+)\.ts"/g, '"../edge/shared/$1"')
    .replace(/"\.\/([a-zA-Z]+)\.ts"/g, '"./$1"')
    .replace(/Deno\.env\.get\("SUPABASE_ANON_KEY"\)/g, "process.env['SUPABASE_PUBLISHABLE_KEY']")
    .replace(/Deno\.env\.get\("([A-Z0-9_]+)"\)/g, "process.env['$1']")
    .replace(/Deno\.env\.get\(([a-zA-Z][\w.]*)\)/g, "process.env[$1]");
}

function toHandler(code) {
  let out = transform(code);
  out = out.replace(
    /^(?:Deno\.)?serve\(\s*async\s*\(\s*(\w+)(?::\s*Request)?\s*\)\s*=>\s*\{/m,
    "export const handler = async ($1: Request): Promise<Response> => {",
  );
  // closing `});` of the serve call -> `};`
  const idx = out.lastIndexOf("});");
  if (idx !== -1) out = out.slice(0, idx) + "};" + out.slice(idx + 3);
  return out;
}

mkdirSync(join(OUT, "shared"), { recursive: true });
mkdirSync(ROUTES, { recursive: true });

// shared modules
for (const f of readdirSync(join(SRC, "_shared"))) {
  if (!f.endsWith(".ts")) continue;
  const code = transform(readFileSync(join(SRC, "_shared", f), "utf8")).replace(
    /"\.\.\/edge\/shared\//g,
    '"./',
  );
  writeFileSync(join(OUT, "shared", f), code);
}

const names = [];
for (const dir of readdirSync(SRC, { withFileTypes: true })) {
  if (!dir.isDirectory() || dir.name === "_shared" || SKIP.has(dir.name)) continue;
  const entry = join(SRC, dir.name, "index.ts");
  if (!existsSync(entry)) continue;
  const code = toHandler(readFileSync(entry, "utf8")).replace(
    /"\.\.\/edge\/shared\//g,
    '"./shared/',
  );
  writeFileSync(join(OUT, `${dir.name}.server.ts`), code);
  names.push(dir.name);
}

// thin API routes
for (const name of names) {
  writeFileSync(
    join(ROUTES, `${name}.ts`),
    `import { createFileRoute } from '@tanstack/react-router'

const run = async ({ request }: { request: Request }) => {
  const { handler } = await import('@/lib/edge/${name}.server')
  return handler(request)
}

export const Route = createFileRoute('/api/public/${name}')({
  server: { handlers: { GET: run, POST: run, OPTIONS: run } },
})
`,
  );
}

console.log(`ported ${names.length} functions:`, names.join(" "));
